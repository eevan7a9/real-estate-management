const { readFileSync, writeFileSync } = require('node:fs');
const { resolve } = require('node:path');
const { parse } = require('dotenv');

const modeOption = process.argv.find((argument) => argument.startsWith('--mode='));
const mode = modeOption?.split('=')[1];

if (mode !== 'development' && mode !== 'production') {
  throw new Error('Use --mode=development or --mode=production.');
}

const production = mode === 'production';
const sourceFile = production ? '.env.production' : '.env';
let values;

try {
  values = parse(readFileSync(resolve(process.cwd(), sourceFile)));
} catch (error) {
  if (error.code === 'ENOENT') {
    throw new Error(`Missing ${sourceFile}. Copy .env.example to ${sourceFile} and set its values.`);
  }
  throw error;
}

const required = (name) => {
  const value = values[name]?.trim();
  if (!value) {
    throw new Error(`Missing required ${name} in ${sourceFile}.`);
  }
  return value;
};

const optional = (name, fallback = '') => values[name]?.trim() || fallback;

const boolean = (name, fallback) => {
  const value = values[name];
  if (value === undefined || value.trim() === '') return fallback;
  if (value === 'true') return true;
  if (value === 'false') return false;
  throw new Error(`${name} in ${sourceFile} must be true or false.`);
};

const environment = {
  production,
  api: {
    server: required('API_SERVER'),
    mapKey: optional('MAP_KEY'),
    googleAuthClientId: optional('GOOGLE_AUTH_CLIENT_ID'),
    webSocketUrl: required('WEBSOCKET_URL')
  },
  map: {
    tiles: {
      default: optional(
        'MAP_TILES_DEFAULT',
        production
          ? 'https://tile.openstreetmap.org/{z}/{x}/{y}.png'
          : 'https://tiles.stadiamaps.com/tiles/alidade_smooth/{z}/{x}/{y}{r}.png?api_key='
      ),
      dark: optional(
        'MAP_TILES_DARK',
        production
          ? 'https://tile.openstreetmap.org/{z}/{x}/{y}.png'
          : 'https://tiles.stadiamaps.com/tiles/alidade_smooth_dark/{z}/{x}/{y}{r}.png?api_key='
      )
    }
  },
  features: {
    restrictedMode: boolean('RESTRICTED_MODE', false),
    restrictedHeading: optional('RESTRICTED_HEADING', 'Restricted'),
    restrictedMessage: optional(
      'RESTRICTED_MESSAGE',
      'This feature is currently disabled in this mode.'
    )
  }
};

const outputFile = 'src/environments/environment.generated.ts';

writeFileSync(
  resolve(process.cwd(), outputFile),
  [
    '// This file is generated by scripts/generate-environments.cjs. Do not edit it directly.',
    `export const environment = ${JSON.stringify(environment, null, 2)} as const;`,
    ''
  ].join('\n')
);
console.info(`Generated ${outputFile} from ${sourceFile}.`);
